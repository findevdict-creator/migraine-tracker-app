/// A day with only the given fields set.
DayInputs day({
  String date = '2026-01-01',
  double? pressureDelta24h,
  double? humidity,
  double? temperatureSwing,
  double? aqiUs,
  double? pollenMax,
  double? uvMax,
  int? lightExposure,
  int? screenExposure,
  int? sleepQuality,
  int? sleepMinutes,
  int? stress,
  int? neckTension,
  int? caffeine,
  int? alcohol,
  int? hydration,
  int? cycleDay,
  int? cycleLength,
}) => DayInputs(
  date: date,
  pressureDelta24h: pressureDelta24h,
  humidity: humidity,
  temperatureSwing: temperatureSwing,
  aqiUs: aqiUs,
  pollenMax: pollenMax,
  uvMax: uvMax,
  lightExposure: lightExposure,
  screenExposure: screenExposure,
  sleepQuality: sleepQuality,
  sleepMinutes: sleepMinutes,
  stress: stress,
  neckTension: neckTension,
  caffeine: caffeine,
  alcohol: alcohol,
  hydration: hydration,
  cycleDay: cycleDay,
  cycleLength: cycleLength,
);

